// Generate static SVG path data for the AZMAN wordmark from the Fraunces font.
// Run with: npm run gen:azman
// Output: lib/azman-paths.ts (committed to the repo)
//
// opentype.js is a devDependency only — its output is committed as a static
// data file, so it is never shipped to the browser.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import opentype from "opentype.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const FONT_PATH = resolve(__dirname, "fraunces-regular.ttf");
const OUT_PATH = resolve(ROOT, "lib", "azman-paths.ts");
const OUT_DIR = dirname(OUT_PATH);

const FONT_SIZE = 1000;
const LETTER_SPACING = 40;
const TEXT = "AZMAN";

const fontBuffer = readFileSync(FONT_PATH);
const font = opentype.parse(
  fontBuffer.buffer.slice(fontBuffer.byteOffset, fontBuffer.byteOffset + fontBuffer.byteLength)
);
const upem = font.unitsPerEm;
const scale = FONT_SIZE / upem;

const glyphs = TEXT.split("").map((ch) => font.charToGlyph(ch));
const widths = glyphs.map((g) => g.advanceWidth * scale);
const totalWidth =
  widths.reduce((a, b) => a + b, 0) + LETTER_SPACING * (TEXT.length - 1);
const ascent = font.ascender * scale;
const descent = -font.descender * scale;
const viewBoxHeight = ascent + descent;

const n = (v) => {
  const s = v.toFixed(2);
  return s.replace(/\.?0+$/, "") || "0";
};

function commandsToPathData(commands, dx, dy) {
  const out = [];
  for (const c of commands) {
    switch (c.type) {
      case "M":
        out.push(`M${n(c.x + dx)} ${n(c.y + dy)}`);
        break;
      case "L":
        out.push(`L${n(c.x + dx)} ${n(c.y + dy)}`);
        break;
      case "Q":
        out.push(
          `Q${n(c.x1 + dx)} ${n(c.y1 + dy)} ${n(c.x + dx)} ${n(c.y + dy)}`
        );
        break;
      case "C":
        out.push(
          `C${n(c.x1 + dx)} ${n(c.y1 + dy)} ${n(c.x2 + dx)} ${n(c.y2 + dy)} ${n(c.x + dx)} ${n(c.y + dy)}`
        );
        break;
      case "Z":
        out.push("Z");
        break;
      default:
        break;
    }
  }
  return out.join(" ");
}

let cursorX = 0;
const paths = glyphs.map((glyph, i) => {
  const p = glyph.getPath(0, 0, FONT_SIZE);
  const d = commandsToPathData(p.commands, cursorX, ascent);
  cursorX += widths[i] + LETTER_SPACING;
  return { letter: TEXT[i], d };
});

const viewBox = `0 0 ${Math.ceil(totalWidth)} ${Math.ceil(viewBoxHeight)}`;

mkdirSync(OUT_DIR, { recursive: true });

const out = `// AUTO-GENERATED by scripts/generate-azman-paths.mjs — do not edit by hand.
// Source: Fraunces144pt-Regular.ttf (SIL OFL 1.1)
// font-size: ${FONT_SIZE}, letter-spacing: ${LETTER_SPACING}
export const AZMAN_PATHS = {
  viewBox: "${viewBox}",
  paths: ${JSON.stringify(paths, null, 2)},
} as const;
`;

writeFileSync(OUT_PATH, out, "utf8");
console.log(`Wrote ${OUT_PATH}`);
console.log(`viewBox: ${viewBox}, ${paths.length} glyphs`);
