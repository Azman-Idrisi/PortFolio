export function fakeLoadEase(t: number): number {
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  for (let i = 0; i < LOAD_POINTS.length - 1; i++) {
    const [t0, v0] = LOAD_POINTS[i];
    const [t1, v1] = LOAD_POINTS[i + 1];
    if (t >= t0 && t <= t1) {
      const k = (t - t0) / (t1 - t0);
      return v0 + k * (v1 - v0);
    }
  }
  return 1;
}
